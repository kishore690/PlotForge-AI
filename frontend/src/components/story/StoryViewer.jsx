import { useState } from "react";
import { motion } from "framer-motion";
import {
  Copy,
  Download,
  Bookmark,
  Share2,
  Clock,
} from "lucide-react";
import Badge from "../common/Badge";

export default function StoryViewer({
  title,
  genre,
  readingTime = 12,
  story,
}) {

  const [bookmarked, setBookmarked] = useState(false);

  const copyStory = () => {
    navigator.clipboard.writeText(story.generatedStory);
    alert("Story copied!");
  };

  return (
    <div className="bg-card border border-border rounded-2xl overflow-hidden flex flex-col h-full">

      {/* Header */}
      <div
        className="relative px-6 py-6 flex items-center gap-4"
        style={{
          background:
            "linear-gradient(135deg,#2a0d0d,#0a0505)",
        }}
      >
        <div className="w-14 h-20 rounded-md shadow-lg bg-gradient-to-br from-primary/80 to-black/60 border border-white/10 flex items-center justify-center shrink-0">
          <span className="font-serif-display text-white/70 text-[10px] text-center px-1">
            {title}
          </span>
        </div>

        <div className="min-w-0">

          <h2 className="font-serif-display text-xl text-ink truncate">
            {title}
          </h2>

          <p className="text-xs text-ink-soft mb-2">
            Generated by PlotForge AI
          </p>

          <div className="flex items-center gap-2">

            <Badge tone="primary">
              {genre}
            </Badge>

            <Badge tone="neutral">
              <Clock size={11} className="mr-1" />
              {readingTime} min
            </Badge>

          </div>

        </div>
      </div>

      {/* Story Content */}

      <div className="flex-1 overflow-y-auto px-8 py-8">

        <motion.div
          initial={{ opacity: 0 }}
          animate={{ opacity: 1 }}
        >

          <div
            className="font-serif-display
                       text-[16px]
                       leading-[2]
                       text-ink-soft
                       whitespace-pre-wrap"
          >
            {story.generatedStory}
          </div>

        </motion.div>

      </div>

      {/* Progress */}

      <div className="h-1 bg-primary w-full"></div>

      {/* Bottom Buttons */}

      <div className="flex items-center justify-between px-6 py-3 border-t border-border">

        <div className="flex gap-2">

          <ActionBtn
            icon={Copy}
            label="Copy"
            onClick={copyStory}
          />

          <ActionBtn
            icon={Download}
            label="Download"
          />

        </div>

        <div className="flex gap-2">

          <ActionBtn
            icon={Bookmark}
            label="Bookmark"
            active={bookmarked}
            onClick={() =>
              setBookmarked(!bookmarked)
            }
          />

          <ActionBtn
            icon={Share2}
            label="Share"
          />

        </div>

      </div>

    </div>
  );
}

function ActionBtn({
  icon: Icon,
  label,
  active,
  onClick,
}) {

  return (
    <button
      title={label}
      onClick={onClick}
      className={`w-9 h-9 rounded-lg flex items-center justify-center transition-colors ${
        active
          ? "bg-primary/20 text-red-400"
          : "hover:bg-card-hover text-ink-soft"
      }`}
    >
      <Icon size={15} />
    </button>
  );

}