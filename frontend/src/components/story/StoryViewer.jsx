import { useState } from "react";
import { motion } from "framer-motion";
import { Copy, Download, Bookmark, Share2, Clock, Feather } from "lucide-react";
import Badge from "../common/Badge";
import { updateStory } from "../../services/libraryService";
import { openStoryPdf } from "../../services/storyPdfService";
import ReadAloudControls from "./ReadAloudControls";
import { getDisplayStoryTitle } from "../../utils/storyTitle";

export default function StoryViewer({ title, genre, readingTime = 12, story, onStoryChange }) {
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState("");
  const displayTitle = getDisplayStoryTitle(title, story?.prompt);

  const copyStory = async () => {
    try {
      await navigator.clipboard.writeText(story.generatedStory || "");
      setMessage("Story copied to clipboard.");
    } catch {
      setMessage("Clipboard access is unavailable in this browser.");
    }
  };

  const downloadStory = async () => {
    setBusy(true);
    setMessage("");
    try {
      await openStoryPdf({ title: displayTitle, genre, generatedStory: story.generatedStory });
      setMessage("Your themed PDF is ready.");
    } catch (error) {
      setMessage(error.message || "Could not create the PDF.");
    } finally {
      setBusy(false);
    }
  };

  const toggleSaved = async () => {
    if (!story.id) {
      setMessage("Save this generated story before bookmarking it.");
      return;
    }
    setBusy(true);
    setMessage("");
    try {
      const updated = await updateStory(story.id, { saved: !story.saved });
      onStoryChange?.(updated);
      setMessage(updated.saved ? "Added to Saved Stories." : "Removed from Saved Stories.");
    } catch (error) {
      setMessage(error.message || "Could not update the bookmark.");
    } finally {
      setBusy(false);
    }
  };

  const shareStory = async () => {
    const text = `${displayTitle}\n\n${story.generatedStory || ""}`;
    try {
      if (navigator.share) await navigator.share({ title: displayTitle, text });
      else {
        await navigator.clipboard.writeText(text);
        setMessage("Story copied so you can share it.");
      }
    } catch (error) {
      if (error.name !== "AbortError") setMessage("Sharing is unavailable in this browser.");
    }
  };

  return (
    <div className="bg-card border border-border rounded-2xl overflow-hidden flex flex-col h-full">
      <div className="relative flex items-start gap-4 border-b border-border bg-gradient-to-br from-[#1F2833] to-[#0B0C10] px-5 py-5 sm:gap-5 sm:px-7 sm:py-7">
        <div aria-hidden="true" className="flex h-20 w-14 shrink-0 items-center justify-center rounded-md border border-white/15 bg-gradient-to-br from-primary/80 via-[#45A29E] to-[#1F2833] shadow-lg sm:h-24 sm:w-[68px]">
          <Feather className="text-[#0B0C10]" size={23} strokeWidth={1.6} />
        </div>
        <div className="min-w-0 flex-1 pt-0.5">
          <h2 className="font-serif-display text-xl leading-snug text-ink [overflow-wrap:anywhere] sm:text-2xl">{displayTitle}</h2>
          <p className="mb-3 mt-1 text-xs text-ink-soft">Generated by PlotForge AI</p>
          <div className="flex items-center gap-2"><Badge tone="primary">{genre}</Badge><Badge tone="neutral"><Clock size={11} className="mr-1" />{readingTime} min</Badge></div>
        </div>
      </div>

      <div className="px-6 pt-4">
        <ReadAloudControls text={story.generatedStory} language={story.language} />
      </div>

      <div className="flex-1 overflow-y-auto px-8 py-8">
        <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="font-serif-display text-[16px] leading-[2] text-ink-soft whitespace-pre-wrap">
          {story.generatedStory}
        </motion.div>
      </div>
      <div className="h-1 bg-primary w-full" />
      <div className="flex items-center justify-between px-6 py-3 border-t border-border">
        <div className="flex gap-2">
          <ActionBtn icon={Copy} label="Copy" onClick={copyStory} />
          <ActionBtn icon={Download} label="Open themed PDF" onClick={downloadStory} disabled={busy} />
        </div>
        <div className="flex gap-2">
          <ActionBtn icon={Bookmark} label={story.saved ? "Remove bookmark" : "Bookmark"} active={story.saved} onClick={toggleSaved} disabled={busy} />
          <ActionBtn icon={Share2} label="Share" onClick={shareStory} />
        </div>
      </div>
      {message && <p role="status" className="px-6 pb-3 text-xs text-ink-soft">{message}</p>}
    </div>
  );
}

function ActionBtn({ icon: Icon, label, active, onClick, disabled }) {
  return <button type="button" title={label} aria-label={label} aria-pressed={active} disabled={disabled} onClick={onClick} className={`w-9 h-9 rounded-lg flex items-center justify-center transition-colors disabled:opacity-50 ${active ? "bg-primary/20 text-primary" : "hover:bg-card-hover text-ink-soft"}`}><Icon size={15} /></button>;
}
